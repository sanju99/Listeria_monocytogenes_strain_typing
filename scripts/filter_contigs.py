def read_in_fasta_file(fasta_file):

    contigs = [(seq.id, seq.seq) for seq in SeqIO.parse(fasta_file, "fasta")]
    
    df_contigs = pd.DataFrame(contigs)
    df_contigs.columns = ['Contig', 'Sequence']
    df_contigs['Length'] = df_contigs['Sequence'].apply(lambda x: len(x))

    return df_contigs



def load_nodes_dmp(nodes_path):
    parent_map = {}
    child_map = {}
    with open(nodes_path, 'r') as f:
        for line in f:
            parts = [x.strip() for x in line.split('|')]
            child_taxid, parent_taxid = int(parts[0]), int(parts[1])
            parent_map[child_taxid] = parent_taxid
            if parent_taxid not in child_map:
                child_map[parent_taxid] = []
            child_map[parent_taxid].append(child_taxid)
    return parent_map, child_map
    

def get_parent_taxids(taxid, parent_map):
    ancestors = []
    while taxid != 1:  # 1 is the root (cellular organisms)
        taxid = parent_map[taxid]
        ancestors.append(taxid)
    return ancestors


def get_child_taxids(taxid, child_map):
    descendants = []
    stack = [taxid]
    while stack:
        current = stack.pop()
        children = child_map.get(current, [])
        descendants.extend(children)
        stack.extend(children)
    return descendants


    
def filter_keep_high_quality_contigs(contigs_file, depth_file, classifications_file, taxid, output_file, min_contig_length, min_median_coverage, kraken_db):

    # genus = species.split(' ')[0]
    
    df_contigs = read_in_fasta_file(contigs_file)
    
    df_depth = pd.read_csv(depth_file, sep="\t", header=None, names=['Contig', 'Position', 'Depth'], compression='infer')
    
    # keep contigs with at least a length of contig_min_length and median coverage of contig_min_median_cov
    # and merge dataframes to filter both at the same time
    df_keep_contigs = df_contigs.query("Length >= @min_contig_length").merge(df_depth.groupby('Contig')['Depth'].agg(['mean', 'median']).reset_index().query("median >= @min_median_coverage"), on='Contig')

    # then IF AND ONLY IF the total classified length to the target species is >95% of the total length (after filtering by contig length and coverage), further filter and keep
    df_kraken = pd.read_csv(classifications_file, sep='\t', header=None, names=['Classified', 'Contig', 'TaxName', 'Length', 'All_Taxa'])

    # separate taxid and name
    df_kraken["TaxID"] = (df_kraken["TaxName"].str.extract(r"\(taxid (\d+)\)")[0]).astype(int)
    df_kraken["TaxName"] = (df_kraken["TaxName"].str.replace(r"\s*\(taxid \d+\)$", "", regex=True))
        
    df_contigs_classifications = df_keep_contigs.merge(df_kraken, on=['Contig', 'Length'])
    assert len(set(df_keep_contigs.Contig) - set(df_contigs_classifications.Contig)) == 0

    # use the taxonomy map to get child and parent taxids of the argument taxid
    parent_map, child_map = load_nodes_dmp(f"{kraken_db}/nodes.dmp")
    
    # use the functions to get all taxids
    parent_taxids = get_parent_taxids(taxid, parent_map)
    child_taxids = get_child_taxids(taxid, child_map)
    
    # keep the argument taxid and children
    select_taxids = [taxid] + child_taxids + parent_taxids

    total_length = df_contigs_classifications.Length.sum()

    # this will also include other Listeria species, which are probably caused by mis-classifications by kraken. It's less likely that those are ACTUALLY present
    # the parent and children taxids will take care of parent nodes of L. monocytogenes, but for example, L. innocua is not a child taxon of L. monocytogenes
    classified_length = df_contigs_classifications.query("TaxID in @select_taxids | TaxName.str.contains('Listeria')").Length.sum()
    
    df_not_taxon = df_contigs_classifications.query("TaxID not in @select_taxids & ~TaxName.str.contains('Listeria')")

    if classified_length / total_length > 0.95:
        if len(df_not_taxon) > 0:
            other_taxa = ','.join(df_not_taxon.TaxName.unique())
            other_taxa_contigs = ','.join(df_not_taxon.Contig.unique())
            logging.info(f"Contigs {other_taxa_contigs} classified as {other_taxa}")

        # keep Listeria contigs too for the final too
        df_contigs_classifications = df_contigs_classifications.query("TaxID in @select_taxids | TaxName.str.contains('Listeria')")
    else:
        raise ValueError(f"Only {np.round(classified_length / total_length * 100, 2)}% of the sequences are classified to taxid {taxid}")
        
    logging.info(f"Keeping {len(df_keep_contigs)}/{len(df_contigs)} contigs with length ≥ {min_contig_length} bp and median coverage ≥ {min_median_coverage}")
    logging.info(f"Keeping {len(df_contigs_classifications)}/{len(df_keep_contigs)} contigs classified as taxid {taxid}, with total length = {classified_length:,} bp, which is {np.round(classified_length / total_length * 100, 2)}% of the pre-kraken-filt length")
    logging.info(f"Minimum contig length = {df_contigs_classifications['Length'].min():,} bp")
    logging.info(f"Minimum contig median coverage = {df_contigs_classifications['median'].min()}")

    with open(output_file, "w+") as file:
        for _, row in df_contigs_classifications.iterrows():
            file.write(f">{row['Contig']}\n")
            file.write(str(row['Sequence']) + '\n')

